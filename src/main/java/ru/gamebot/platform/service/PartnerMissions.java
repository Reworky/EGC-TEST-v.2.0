    public static final List<PartnerMission> ALL = List.of(OTP, T_BLACK, T_MOBILE, VTB, ALFA, FORA, PSB, UBRR, SOVCOM, OTPCREDIT, TBANKCREDIT, TBANKBLACK, VTBCREDIT);

    /** Партнёрские привилегии (статус партнёра, курс вывода 100%, разовый запас вывода, бейдж «Банкир EGC») даёт только квест из WithdrawalPartners.ALL (сейчас ОТП, решение
     *  владельца 09.11.2026); остальные квесты банков и операторов только платят награду. */
    public static boolean grantsPartner(PartnerMission pm) {
        return pm != null && WithdrawalPartners.ALL.stream().anyMatch(b -> b.mission().key().equals(pm.key()));
    }

    /** Конфиг миссии квеста по его названию (null, если квест не партнёрская миссия). */
    public static PartnerMission forQuest(Quest quest) {
        if (quest == null || quest.getTitle() == null) return null;
        for (PartnerMission pm : ALL) {
            if (pm.questTitle().equals(quest.getTitle())) return pm;
        }
        return null;
    }

    /** Ссылка на заявку с номером заявки игрока на квест (?sid=N перед #карточкой): витрина кладёт его в SubID 4 ссылки LeadGid, по нему постбек находит игрока. Без номера - обычная ссылка. */
    public static String applyLinkFor(PartnerMission pm, Long submissionId) {
        if (pm == null || pm.applyLink() == null) return null;
        String link = pm.applyLink();
        if (submissionId == null) return link;
        int hash = link.indexOf('#');
        String base = hash < 0 ? link : link.substring(0, hash);
        String tail = hash < 0 ? "" : link.substring(hash);
        return base + (base.contains("?") ? "&" : "?") + "sid=" + submissionId + tail;
    }

    public static Optional<PartnerMission> forGame(String gameName) {
        return ALL.stream().filter(pm -> pm.gameName().equals(gameName)).findFirst();
    }
